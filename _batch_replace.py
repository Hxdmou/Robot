    if l.strip().startswith("'【") and is_stale(l):
        part = line_to_part.get(i, 'UNKNOWN')
        if part in REPLACEMENTS:
            if part not in replacement_idx:
                replacement_idx[part] = 0
            idx = replacement_idx[part]
            if idx < len(REPLACEMENTS[part]):
                # 保持原始缩进
                indent = len(l) - len(l.lstrip())
                new_content = REPLACEMENTS[part][idx]
                # 确保以 ' 开头和 ' 结尾（或 ',）
                stripped = l.strip()
                if stripped.endswith("',"):
                    lines[i] = ' ' * indent + "'" + new_content + "',"
