# ============ 执行替换（每条替换内容只用一次，按文件行序消费） ============
replaced_total = 0
replaced_details = []
not_matched = []
pair_used = [False] * len(REPLACEMENT_PAIRS)

for i, l in enumerate(lines):
    stripped = l.strip()
    if not (stripped.startswith("'【") or stripped.startswith('"【') or stripped.startswith("['【")):
        continue
    if not is_stale_line(l):
        continue
    matched = False
    for pi, (key, new_content) in enumerate(REPLACEMENT_PAIRS):
        if pair_used[pi]:
            continue
        if key in l:
            indent = len(l) - len(l.lstrip())
            if stripped.startswith("['【"):
                lines[i] = ' ' * indent + "['" + new_content + "',"
            elif stripped.startswith('"'):
                lines[i] = ' ' * indent + '"' + new_content + '",'
            else:
                lines[i] = ' ' * indent + "'" + new_content + "',"
            replaced_details.append(f'  L{i+1} → {new_content[:50]}...')
            replaced_total += 1
            pair_used[pi] = True
            matched = True
            break
    if not matched:
        not_matched.append(f'  L{i+1}: {stripped[:80]}...')

# ============ 写回文件 ============
