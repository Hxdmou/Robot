replaced_by_part = {}

for i, l in enumerate(lines):
    s = l.strip()
    is_content = (s.startswith("'【") or s.startswith('"【') or
                  s.startswith("['【") or s.startswith('["【'))
    if not is_content:
        continue
    if not is_stale_line(l):
        continue
    part = line_to_part.get(i, 'UNKNOWN')
    if part in REPLACEMENTS and replacement_idx[part] < len(REPLACEMENTS[part]):
        indent = len(l) - len(l.lstrip())
        new_content = REPLACEMENTS[part][replacement_idx[part]]
        # 保持原始引号格式
        if s.startswith("['【") or s.startswith('["【'):
            lines[i] = ' ' * indent + "['" + new_content + "',"
        else:
            lines[i] = ' ' * indent + "'" + new_content + "',"
        replacement_idx[part] += 1
        replaced_total += 1
        replaced_by_part[part] = replaced_by_part.get(part, 0) + 1

