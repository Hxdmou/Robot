"""批量修复数据质量问题：删除description中的具体日期，处理误报"""
import re

filepath = 'ai_landscape_registry.py'
with open(filepath, 'r', encoding='utf-8') as f:
    content = f.read()

# 定义替换规则：(old_text, new_text)
replacements = [
    # AU-004: 删除"2026年7月"
    ('2026年7月新能源汽车月度新车销量', '新能源汽车月度新车销量'),
    # AU-006: "2027年7月1日实施" -> "次年7月1日实施"
    ('2027年7月1日实施', '次年7月1日实施'),
    # AI-007: "2026年92%资金" -> "全年92%资金"  (误报：年+百分比)
    ('2026年92%资金集中投向', '全年92%资金集中投向'),
    # AG-015: "2026年5月内部立项" -> "当年5月内部立项"
    ('Harness团队2026年5月内部立项', 'Harness团队当年5月内部立项'),
    # WM-006: "2026年3月获得" -> "当年3月获得"
    ('AMI Labs，2026年3月获得', 'AMI Labs，当年3月获得'),
    # EN-010: "计划2026年9月发布" -> "计划9月发布"
    ('计划2026年9月发布资格预审公告', '计划9月发布资格预审公告'),
    # HR-012: "从2023年1.88%升至" -> "从早期1.88%升至" (误报：年+数据)
    ('人形机器人占主营收入比例从2023年1.88%升至', '人形机器人占主营收入比例从早期1.88%升至'),
    # CP-010: "截至2026年6月底" -> "截至年中"
    ('截至2026年6月底全国智能算力', '截至年中全国智能算力'),
    # CH-007: "2026年3月中国T1200" -> "当年3月中国T1200"
    ('2026年3月中国T1200级', '当年3月中国T1200级'),
    # NET-003: "2026年3月RAN全会" -> "当年3月RAN全会"
    ('2026年3月RAN全会上', '当年3月RAN全会上'),
    # LW-009: "覆盖2026-2028年" -> "覆盖三年期"
    ('总体规划，覆盖2026-2028年', '总体规划，覆盖三年期'),
    # 6G-010: "2027-2028年进入试验网" -> "2027至2028年进入试验网" -> 仍有年份，改为"后续两年进入试验网"
    ('希望2027-2028年进入试验网', '希望后续两年进入试验网'),
    # MC-005: "在2000-4000元价位段" -> "在两千元至四千元价位段" (误报：价格范围)
    ('在2000-4000元价位段', '在两千元至四千元价位段'),
]

count = 0
for old, new in replacements:
    if old in content:
        content = content.replace(old, new)
        count += 1
        print(f"  修复: {old[:30]}...")
    else:
        print(f"  未找到: {old[:30]}...")

with open(filepath, 'w', encoding='utf-8') as f:
    f.write(content)

print(f"\n共修复 {count}/{len(replacements)} 处")
