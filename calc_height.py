"""
精确估算文本高度 - 修正字符密度
10pt微软雅黑中文：每个字符约0.12-0.14英寸宽（方块字，宽≈字号/72*0.9）
"""

FONT_SIZE_PT = 10
LINE_HEIGHT_RATIO = 1.1
LINE_HEIGHT_IN = (FONT_SIZE_PT / 72) * LINE_HEIGHT_RATIO * 1.05  # 增加5%行高余量
print(f'单行高度: {LINE_HEIGHT_IN:.4f}英寸')

# 修正：实际PPT中10pt中文，每英寸约放7.5-8个中文字符（方块字）
# 每个ASCII字符宽度约0.06-0.07英寸

def estimate_lines(text, width_in, cn_chars_per_inch=7.2):
    """估算折行数 - cn_chars_per_inch：每英寸放多少个中文字符"""
    cn_char_w = 1.0 / cn_chars_per_inch  # 每个中文字符宽度
    en_char_w = cn_char_w * 0.55         # 每个英文/数字宽度
    total_w = 0
    for c in text:
        if ord(c) > 127:  # 中文/全角
            total_w += cn_char_w
        else:  # ASCII半角
            total_w += en_char_w
    import math
    return math.ceil(total_w / width_in)

